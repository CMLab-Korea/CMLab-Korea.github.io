/* CMLab website: dependency-free client interactions. All research content is editable JSON. */
(() => {
  'use strict';
  const $ = (s, p=document) => p.querySelector(s);
  const $$ = (s, p=document) => [...p.querySelectorAll(s)];
  const page = document.body.dataset.page;
  const nav = $('.nav-links');
  const toggle = $('.menu-toggle');
  if (toggle && nav) {
    function setMenu(open) {
      nav.classList.toggle('open', open);
      toggle.setAttribute('aria-expanded', String(open));
      toggle.setAttribute('aria-label', open ? 'Close navigation' : 'Open navigation');
    }
    toggle.addEventListener('click', () => setMenu(!nav.classList.contains('open')));
    document.addEventListener('keydown', event => {
      if (event.key === 'Escape' && nav.classList.contains('open')) {
        setMenu(false);
        toggle.focus();
      }
    });
  }
  $$('[data-nav]').forEach(link => {
    if (link.dataset.nav === page) {
      link.classList.add('active');
      link.setAttribute('aria-current', 'page');
    }
  });
  const progress = $('#scroll-progress');
  const onScroll = () => {
    const max = document.documentElement.scrollHeight - innerHeight;
    if (progress) progress.style.width = (max > 0 ? (scrollY / max * 100) : 0).toFixed(2) + '%';
  };
  addEventListener('scroll', onScroll, {passive:true});onScroll();
  if ('IntersectionObserver' in window) {
    const o = new IntersectionObserver((entries) => entries.forEach(e => {if (e.isIntersecting) {e.target.classList.add('in-view');o.unobserve(e.target)}}), {threshold:.08});
    $$('.reveal').forEach(el => o.observe(el));
  } else {$$('.reveal').forEach(el=>el.classList.add('in-view'))}

  /* Remote JS files are generated by the pre-existing CMLab GitHub Actions.
     Loading scripts rather than cross-origin fetch supports both GitHub Pages
     and the legacy Google Sites HTML embed. */
  function putStat(name, value) {
    if (!Number.isSafeInteger(value) || value < 0) return;
    $$(`[data-stat="${name}"]`).forEach(el => {el.textContent = value.toLocaleString('en-US')});
  }
  window.cmlabStatsApply = stats => {
    if (!stats || !['total','conference','journal','preprint'].every(k=>Number.isSafeInteger(stats[k]) && stats[k]>=0)) return;
    if (stats.total !== stats.conference + stats.journal) return;
    ['total','conference','journal','preprint'].forEach(k=>putStat(k,stats[k]));
  };
  window.cmlabScholarStatsApply = stats => {
    if (!stats || stats.scholar_author_id !== 'D5yPXMsAAAAJ') return;
    if (!Number.isSafeInteger(stats.citations) || !Number.isSafeInteger(stats.h_index) || stats.h_index>stats.citations) return;
    putStat('citations',stats.citations);putStat('h_index',stats.h_index);
  };
  function remoteScript(file) {
    const tag = document.createElement('script');
    tag.async = true;
    tag.src = 'https://cmlab-korea.github.io/cmlab-web-assets/data/'+file+'?v='+Math.floor(Date.now()/3600000);
    tag.onerror = () => console.info('Live metrics temporarily unavailable; showing verified fallback values.');
    document.head.appendChild(tag);
  }
  remoteScript('publication-stats.js');remoteScript('scholar-stats.js');

  /* Import only repository-owned JSON, never executable page HTML. */
  async function getData(file) {
    const r = await fetch('data/'+file, {cache:'no-cache'});
    if (!r.ok) throw Error(`Unable to load ${file}`);
    return r.json();
  }
  function node(tag, cls, content) {const n=document.createElement(tag);if(cls)n.className=cls;if(content!==undefined)n.textContent=content;return n}
  function safeURL(value) {try{const u=new URL(value,location.href);return ['https:','http:'].includes(u.protocol)?u.href:'#'}catch{return '#'}}

  if (page==='home') {
    getData('news.json').then(items=>{
      const target=$('#news-list'); if(!target) return;target.replaceChildren();
      items.slice(0,4).forEach(x=>{
        const a=node('a','news-item');a.href=safeURL(x.link);a.target='_blank';a.rel='noopener noreferrer';
        const d=node('time','',x.date);const text=node('span','',x.headline);const arrow=node('b','','↗');a.append(d,text,arrow);target.appendChild(a);
      });
    }).catch(()=>{const target=$('#news-list');if(target)target.textContent='Visit the original CMLab site for recent news.'});

    const canvas=$('#particle-canvas');
    if (canvas && !matchMedia('(prefers-reduced-motion: reduce)').matches) {
      const ctx=canvas.getContext('2d'); let dpr=1,w=0,h=0,pts=[];let visible=true;
      function resize(){const rect=canvas.getBoundingClientRect();dpr=Math.min(devicePixelRatio||1,2);w=rect.width;h=rect.height;canvas.width=Math.max(1,Math.round(w*dpr));canvas.height=Math.max(1,Math.round(h*dpr));ctx.setTransform(dpr,0,0,dpr,0,0);pts=Array.from({length:Math.min(65,Math.floor(w/7))},()=>({x:Math.random()*w,y:Math.random()*h,r:.4+Math.random()*1.4,s:.1+Math.random()*.27}))}
      resize(); if ('ResizeObserver' in window) new ResizeObserver(resize).observe(canvas);else addEventListener('resize',resize);
      document.addEventListener('visibilitychange',()=>{visible=!document.hidden});
      function frame(){if (visible){ctx.clearRect(0,0,w,h);ctx.fillStyle='rgba(163,195,255,.52)';for(const p of pts){p.y-=p.s;if(p.y<0)p.y=h;ctx.beginPath();ctx.arc(p.x,p.y,p.r,0,Math.PI*2);ctx.fill()}}requestAnimationFrame(frame)}requestAnimationFrame(frame);
    }
  }
  if(page==='publications') {
    const container=$('#publication-list'),search=$('#paper-search'),type=$('#paper-type'),year=$('#paper-year'),venueFilter=$('#paper-venue'),area=$('#paper-area'),counter=$('#paper-count');
    getData('publications.json').then(items=>{
      const years=[...new Set(items.map(x=>x.year))].sort((a,b)=>b-a);
      years.forEach(y=>{const opt=node('option','',String(y));opt.value=String(y);year.appendChild(opt)});
      [...new Set(items.map(p => p.venue))].sort().forEach(venue => {
        const option = node('option', '', venue);
        option.value = venue;
        venueFilter.append(option);
      });
      function show(){
        const query=(search.value||'').trim().toLowerCase();
        const result=items.filter(p=>(type.value==='all'||p.type===type.value)&&(year.value==='all'||String(p.year)===year.value)&&(venueFilter.value==='all'||p.venue===venueFilter.value)&&(area.value==='all'||p.area===area.value)&&(!query||[p.short, p.title, p.venue, p.area, p.authors].join(' ').toLowerCase().includes(query)));
        counter.textContent=`${result.length} OF ${items.length} ENTRIES`;
        container.replaceChildren();
        if(!result.length){container.appendChild(node('p','archive-notice','No records match these filters.'));return}
        for(const p of result){
          const row=node('article','paper-row rich-paper');
          const venue=node('div','venue-column');
          venue.append(node('span','venue-abbr',p.venue_short || (p.venue+' '+p.year)),node('span','venue-kind',p.type==='Preprint'?'UNDER REVIEW':p.type.toUpperCase()));
          const teaser=node('div','paper-teaser');
          if(p.teaser_video){
            const video=node('video','paper-video');video.src=p.teaser_video;video.muted=true;video.controls=true;video.playsInline=true;video.preload='none';video.poster=p.teaser;video.setAttribute('aria-label',p.teaser_video_label);teaser.append(video);
          } else if(p.teaser){
            const image=node('img','paper-image');image.src=p.teaser;image.alt=p.teaser_alt;image.loading='lazy';image.onerror=()=>{image.remove();teaser.append(node('span','teaser-placeholder',p.short))};teaser.append(image);
          } else {teaser.append(node('span','teaser-placeholder',p.short));}
          const body=node('div','paper-rich-body');
          const title=node('h3');const link=node('a','paper-title',p.title);link.href=safeURL(p.url);link.target='_blank';link.rel='noopener noreferrer';title.append(link);
          const over=node('div','paper-overline',p.short);body.append(over,title);
          if(p.authors){
            const line=node('p','paper-authors');
            const names=p.authors.split(/, and |, | and /).map(x=>x.trim()).filter(Boolean);
            names.forEach((name,i)=>{
              if(i)line.append(document.createTextNode(', '));
              const plain=name.replace(/[†*‡]/g,'').trim();
              const isPI=plain==='Jihyong Oh';
              const isMember=p.cmlab_lead_authors?.includes(plain);
              line.append(node('span',isPI?'author-pi':isMember?'author-cmlab':'',name));
            });body.append(line);
          }else{body.append(node('p','paper-authors muted','Authors: see original publication entry'));}
          if(p.affiliations?.length){
            const chips=node('div','paper-affiliations');p.affiliations.forEach(name=>chips.append(node('span','affiliation-tag',name)));body.append(chips);
          }
          const footer=node('div','paper-meta');footer.append(node('span','',p.venue+' · '+p.year));
          const archive = p.url === 'https://cmlab.cau.ac.kr/publications';
          for (const [label, href] of [[archive ? 'Archive' : 'Paper', p.url], ['Project', p.project_url], ['Code', p.code_url]]) {
            if (!href) continue;
            const open = node('a', 'paper-open', label + ' ↗');
            open.href = safeURL(href);
            open.target = '_blank';
            open.rel = 'noopener noreferrer';
            footer.append(open);
          }
          body.append(footer);
          row.append(venue,teaser,body);container.appendChild(row);
        }
      }
      [search,type,year,venueFilter,area].forEach(x=>x.addEventListener(x===search?'input':'change',show));show();
    }).catch(()=>{container.textContent='Publication data is unavailable. See the original CMLab publications archive.'});
  }
  if(page==='people'){
    getData('people.json').then(items=>{
      const map={core:'#core-people',intern:'#intern-people'};
      for(const [group,sel] of Object.entries(map)){
        const target=$(sel);if(!target)continue;
        items.filter(x=>x.group===group).forEach(p=>{
          const article=node('article','person-card');
          const initials=p.name.split(' ').map(n=>n[0]).slice(0,2).join('').toUpperCase();
          article.append(node('div','person-avatar',initials),node('h3','',p.name),node('p','',p.degree));
          if(p.note)article.appendChild(node('small','',p.note));target.appendChild(article);
        });
      }
    }).catch(()=>{const target=$('#core-people');if(target)target.textContent='Member data unavailable. Visit the original CMLab Students page.'});
  }
  if (page==='people') {
    getData('collaborators.json').then(items=>{
      const target=$('#collaborators-grid');if(!target)return;
      const order=['Academia','Research Institute','Industry'];
      order.forEach(category=>{
        const group=items.filter(x=>x.category===category);if(!group.length)return;
        const heading=node('h3','collaborator-group-heading',category);target.append(heading);
        const wrap=node('div','collab-cards');
        group.forEach(c=>{
          const a=node('a','collab-card');a.href=safeURL(c.url);a.target='_blank';a.rel='noopener noreferrer';
          const badge=node('div','collab-badge',c.institution.replace(/[^A-Za-z\s]/g,'').split(/\s+/).map(t=>t[0]).slice(0,3).join('').toUpperCase());
          const content=node('div','collab-content');content.append(node('strong','',c.institution),node('span','collab-person',c.person),node('small','',c.unit));
          if(c.works?.length)content.append(node('span','collab-work',c.works.slice(0,3).join(' · ')));
          a.append(badge,content,node('span','collab-arrow','↗'));wrap.append(a);
        });target.append(wrap);
      });
    }).catch(()=>{const target=$('#collaborators-grid');if(target)target.textContent='See the collaborators section on the original CMLab website.'});
  }

})();
